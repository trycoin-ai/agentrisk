DEFAULT_PRESET = "balanced"


# --------------------------------------------------------------------------- #
# Serialization helpers                                                       #
# --------------------------------------------------------------------------- #


def _num(v: float) -> int | float:
    """Render 25.0 as 25 for clean YAML, but keep genuine decimals."""
    f = float(v)
    return int(f) if f == int(f) else f


def policy_to_dict(p: Policy) -> dict[str, Any]:
    """Ordered, YAML-safe dict. Optional numeric limits are omitted when unset."""
    d: dict[str, Any] = {
        "schema_version": p.schema_version,
        "revision": p.revision,
        "preset": p.preset,
        "created_at": p.created_at,
        "updated_at": p.updated_at,
    }
    if p.notes is not None:
        d["notes"] = p.notes

    limits: dict[str, Any] = {}
    if p.limits.max_single_position_pct is not None:
        limits["max_single_position_pct"] = _num(p.limits.max_single_position_pct)
    limits["max_sector_pct"] = {k: _num(v) for k, v in sorted(p.limits.max_sector_pct.items())}
    limits["max_tag_pct"] = {k: _num(v) for k, v in sorted(p.limits.max_tag_pct.items())}
    limits["max_asset_class_pct"] = {
        k: _num(v) for k, v in sorted(p.limits.max_asset_class_pct.items())
    }
    limits["warn_at_utilization"] = _num(p.limits.warn_at_utilization)
    d["limits"] = limits

    d["asset_rules"] = {
        "crypto": p.asset_rules.crypto.value,
        "options": p.asset_rules.options.value,
        "margin": p.asset_rules.margin.value,
    }

    order_rules: dict[str, Any] = {}
    if p.order_rules.max_order_pct_of_portfolio is not None:
        order_rules["max_order_pct_of_portfolio"] = _num(p.order_rules.max_order_pct_of_portfolio)
    if p.order_rules.max_order_value is not None:
        order_rules["max_order_value"] = _num(p.order_rules.max_order_value)
    if p.order_rules.min_cash_pct is not None:
        order_rules["min_cash_pct"] = _num(p.order_rules.min_cash_pct)
    d["order_rules"] = order_rules

    d["restricted"] = {
        "never_trade": list(p.restricted.never_trade),
        "warn_list": list(p.restricted.warn_list),
    }
    d["data_rules"] = {"max_snapshot_age_hours": _num(p.data_rules.max_snapshot_age_hours)}
    return d


def render_yaml(p: Policy) -> str:
    header = (
        "# AgentRisk policy file. Generated by generate_risk_policy; you can edit it by hand.\n"
        "# Percentages are 0-100. Absence of a limit means that limit is not enforced.\n"
    )
    body = yaml.safe_dump(policy_to_dict(p), sort_keys=False, default_flow_style=False)
    return header + body


def policy_sha256(p: Policy) -> str:
    return hashlib.sha256(render_yaml(p).encode("utf-8")).hexdigest()


def coerce_policy(policy: PolicyInput) -> Policy:
    if isinstance(policy, Policy):
        return policy
    if isinstance(policy, dict):
        return Policy(**policy)
    raise TypeError("policy must be a Policy, a dict, or None")


# --------------------------------------------------------------------------- #
# Resolution (used by check_trade_risk / analyze_portfolio_risk)              #
# --------------------------------------------------------------------------- #


def resolve_policy(
    policy: PolicyInput = None,
    policy_path: str | None = None,
    home: str | None = None,
) -> tuple[Policy | None, dict[str, Any]]:
    """Inline policy > explicit path > default location. Returns (policy, meta)."""
    if policy is not None:
        pol = coerce_policy(policy)
        return pol, {"source": "inline", "path": None, "revision": pol.revision,
                     "sha256": policy_sha256(pol)}

    path = resolve_policy_path(policy_path, home)
    if path.exists():
        try:
            data = yaml.safe_load(path.read_text("utf-8")) or {}
            pol = Policy(**data)
        except Exception as exc:  # noqa: BLE001 - never surface raw file contents
            raise PolicyLoadError(str(path)) from exc
        return pol, {"source": "file", "path": str(path), "revision": pol.revision,
                     "sha256": policy_sha256(pol)}

    return None, {"source": "none", "path": str(path), "revision": None, "sha256": None}


# --------------------------------------------------------------------------- #
# Diffing                                                                     #
# --------------------------------------------------------------------------- #


def _flatten(p: Policy) -> dict[str, Any]:
    flat: dict[str, Any] = {
        "limits.max_single_position_pct": p.limits.max_single_position_pct,
        "limits.warn_at_utilization": p.limits.warn_at_utilization,
        "asset_rules.crypto": p.asset_rules.crypto.value,
        "asset_rules.options": p.asset_rules.options.value,
        "asset_rules.margin": p.asset_rules.margin.value,
        "order_rules.max_order_pct_of_portfolio": p.order_rules.max_order_pct_of_portfolio,
        "order_rules.max_order_value": p.order_rules.max_order_value,
        "order_rules.min_cash_pct": p.order_rules.min_cash_pct,
        "data_rules.max_snapshot_age_hours": p.data_rules.max_snapshot_age_hours,
    }
    for bucket_attr, prefix in (
        (p.limits.max_sector_pct, "limits.max_sector_pct"),
        (p.limits.max_tag_pct, "limits.max_tag_pct"),
        (p.limits.max_asset_class_pct, "limits.max_asset_class_pct"),
    ):
        for k, v in bucket_attr.items():
            flat[f"{prefix}.{k}"] = v
    return flat


_ASSET_ORDER = {"allow": 0, "warn": 1, "block": 2}


def _tightness(key: str, val: Any) -> float:
    if val is None:
        return float("-inf")
    if key.startswith("asset_rules."):
        return float(_ASSET_ORDER[val])
    if "min_cash" in key:
        return float(val)
    # everything else (caps, warn_at_utilization, snapshot age): lower value = tighter
    return -float(val)


def _classify(key: str, old: Any, new: Any) -> str:
    t_old, t_new = _tightness(key, old), _tightness(key, new)
    if t_new > t_old:
        return "tightening"
    if t_new < t_old:
        return "loosening"
    return "neutral"


def diff_policies(old: Policy, new: Policy) -> list[PolicyDiffEntry]:
    entries: list[PolicyDiffEntry] = []
    fo, fn = _flatten(old), _flatten(new)
    for key in sorted(set(fo) | set(fn)):
        o, n = fo.get(key), fn.get(key)
        if o == n:
            continue
        entries.append(PolicyDiffEntry(field=key, old=o, new=n, classification=_classify(key, o, n)))

    # Restricted lists: element-wise (adding is tightening, removing is loosening).
    for attr, prefix in (("never_trade", "restricted.never_trade"),
                         ("warn_list", "restricted.warn_list")):
        old_set = set(getattr(old.restricted, attr))
        new_set = set(getattr(new.restricted, attr))
        for sym in sorted(new_set - old_set):
            entries.append(PolicyDiffEntry(field=prefix, old=None, new=sym, classification="tightening"))
        for sym in sorted(old_set - new_set):
            entries.append(PolicyDiffEntry(field=prefix, old=sym, new=None, classification="loosening"))
    return entries


# --------------------------------------------------------------------------- #
# Deep-merge for `changes` (setting a value to None removes it)               #
# --------------------------------------------------------------------------- #


def _deep_merge(base: dict, patch: dict) -> dict:
    out = copy.deepcopy(base)
    for k, v in patch.items():
        if v is None:
            out.pop(k, None)
        elif isinstance(v, dict) and isinstance(out.get(k), dict):
            out[k] = _deep_merge(out[k], v)
        else:
            out[k] = v
    return out


