def generate_risk_policy(
    mode: str = "create",
    *,
    preset: str | None = None,
    fields: dict | None = None,
    changes: dict | None = None,
    confirm: bool = False,
    policy_path: str | None = None,
    home: str | None = None,
    now: datetime | None = None,
) -> PolicyResult:
    now = now or datetime.now(timezone.utc)
    today = now.date().isoformat()
    path = resolve_policy_path(policy_path, home)

    if mode == "create":
        return _create(preset, fields, confirm, path, today, now)
    if mode == "update":
        return _update(changes, confirm, path, today, now)
    if mode == "show":
        return _show(path)
    raise ValueError(f"unknown mode {mode!r} (expected create | update | show)")


def _build_result(mode: str, pol: Policy, path: Path, written: bool,
                  requires_confirmation: bool, message: str,
                  diff: list[PolicyDiffEntry] | None = None) -> PolicyResult:
    return PolicyResult(
        mode=mode,
        written=written,
        path=str(path),
        requires_confirmation=requires_confirmation,
        message=message,
        policy=policy_to_dict(pol),
        yaml=render_yaml(pol),
        summary=messages.policy_summary(pol),
        diff=diff,
    )


def _create(preset: str | None, fields: dict | None, confirm: bool,
            path: Path, today: str, now: datetime) -> PolicyResult:
    if path.exists():
        raise ValueError(
            f"a policy already exists at {path}; use mode='update' to change it "
            f"(create never overwrites an existing policy)"
        )
    preset_name = preset or DEFAULT_PRESET
    if preset_name not in PRESETS:
        raise ValueError(f"unknown preset {preset_name!r} (expected one of {sorted(PRESETS)})")

    merged = _deep_merge(PRESETS[preset_name], fields or {})
    merged.update(
        schema_version=1, revision=1, preset=preset_name,
        created_at=today, updated_at=today,
    )
    pol = Policy(**merged)  # strict validation (unknown fields raise)

    if confirm:
        atomic_write_text(path, render_yaml(pol))
        audited = audit.record(path, "policy_created", {"revision": 1, "preset": preset_name,
                                                        "path": str(path)}, now=now)
        if not audited:
            # A policy change we cannot audit breaks the "every change is logged"
            # guarantee, so fail closed: roll the write back rather than leave an
            # unaudited policy in place.
            try:
                path.unlink()
            except OSError:  # pragma: no cover - defensive
                pass
            raise RuntimeError(
                f"policy created at {path} but the audit log could not be written; "
                f"rolled the change back"
            )
        return _build_result("create", pol, path, True, False,
                             f"Policy created at {path} (revision 1).")
    return _build_result(
        "create", pol, path, False, True,
        "Proposed a new policy. Review the rules, then call again with confirm=true to write it.",
    )


def _update(changes: dict | None, confirm: bool, path: Path,
            today: str, now: datetime) -> PolicyResult:
    if not path.exists():
        raise ValueError(
            f"no policy exists at {path} to update; use mode='create' first"
        )
    if not changes:
        raise ValueError("update mode requires a non-empty 'changes' object")

    current = Policy(**(yaml.safe_load(path.read_text("utf-8")) or {}))
    merged = _deep_merge(policy_to_dict(current), changes)
    merged["schema_version"] = 1
    merged["created_at"] = current.created_at or today
    proposed = Policy(**merged)
    # Bump metadata after validation so revision/timestamps are authoritative.
    proposed = proposed.model_copy(update={"revision": current.revision + 1, "updated_at": today})

    diff = diff_policies(current, proposed)
    loosenings = [e for e in diff if e.classification == "loosening"]

    if not diff:
        return _build_result("update", current, path, False, False,
                             "No changes: the requested update matches the current policy.", diff=[])

    if confirm:
        # Archive the outgoing revision, then write the new one.
        hist = history_dir(path) / f"rev-{current.revision}.yaml"
        atomic_write_text(hist, render_yaml(current))
        atomic_write_text(path, render_yaml(proposed))
        audited = audit.record(path, "policy_updated", {
            "from_revision": current.revision,
            "to_revision": proposed.revision,
            "diff": [e.model_dump() for e in diff],
            "loosenings": [e.field for e in loosenings],
        }, now=now)
        if not audited:
            # Fail closed: restore the prior revision so an unauditable change does
            # not silently take effect.
            atomic_write_text(path, render_yaml(current))
            try:
                hist.unlink()
            except OSError:  # pragma: no cover - defensive
                pass
            raise RuntimeError(
                f"policy update at {path} could not be audited; reverted to "
                f"revision {current.revision}"
            )
        msg = f"Policy updated to revision {proposed.revision}."
        if loosenings:
            msg += f" Note: {len(loosenings)} change(s) RELAXED your guardrails."
        return _build_result("update", proposed, path, True, False, msg, diff=diff)

    if loosenings:
        fields_txt = ", ".join(e.field for e in loosenings)
        msg = (
            f"Proposed update relaxes {len(loosenings)} guardrail(s): {fields_txt}. "
            f"Confirm with the user, then call again with confirm=true to apply."
        )
    else:
        msg = "Proposed update. Call again with confirm=true to apply."
    return _build_result("update", proposed, path, False, True, msg, diff=diff)


def _show(path: Path) -> PolicyResult:
    if not path.exists():
        return PolicyResult(
            mode="show", written=False, path=str(path), requires_confirmation=False,
            message=f"No policy found at {path}. Create one with mode='create'.",
        )
    pol = Policy(**(yaml.safe_load(path.read_text("utf-8")) or {}))
    return _build_result("show", pol, path, False, False,
                        f"Current policy at {path} (revision {pol.revision}).")
