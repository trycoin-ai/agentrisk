"""Risk-policy lifecycle: create, update, and show.

Updates are a two-call flow: a proposal with a diff that flags loosening changes,
then a write only when confirm=True. Every change is versioned and audited.
"""

from __future__ import annotations

import copy
import hashlib
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import yaml

from . import audit, messages
from .models import Policy, PolicyDiffEntry, PolicyResult
from .store import atomic_write_text, history_dir, resolve_policy_path

PolicyInput = Policy | dict | None


class PolicyLoadError(Exception):
    """A policy file exists but could not be parsed or validated.

    The message is deliberately generic (path only): the underlying parser error
    can echo file contents, and a caller-controlled ``policy_path`` must not become
    a way to read arbitrary file data back through an error string.
    """

    def __init__(self, path: str) -> None:
        self.path = path
        super().__init__(f"policy file at {path} could not be read or validated")

